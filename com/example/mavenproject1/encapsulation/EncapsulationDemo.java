package com.example.mavenproject1.encapsulation;

public class EncapsulationDemo {
	private int a=10;
	int b=20;
	protected int c=30;
	public int d=40;
	
	private void f1() {
		System.out.println("i am in f1");
	}
	 void f2() {
		System.out.println("i am in f2");
	}
	protected void f3() {
		System.out.println("i am in f3");
	}
	public void f4() {
		System.out.println("i am in f4");
	}
	
}
